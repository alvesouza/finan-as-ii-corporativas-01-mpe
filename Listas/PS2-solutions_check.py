"""Check every number printed in PS2-solutions.tex and PS2-solutions-short.tex.

Run: python -I Listas/PS2-solutions_check.py
Prints "PASS <n> checks" or stops at the first failing assert. It also (re)writes
Listas/PS2-solutions-table.tex, the full D = 0.01..1.00 table of Exercise 1(e'),
which PS2-solutions.tex includes with \\input.
Tolerance: |computed - printed| <= half a unit in the last printed digit
(passed explicitly to each check as `tol`).
"""
from pathlib import Path

n = 0


def check(value, printed, tol):
    """Assert that `value` rounds to the number printed in the solutions.

    value   -- number computed here from the statement's data.
    printed -- number as displayed in the .tex.
    tol     -- half a unit of the last printed digit.
    """
    global n
    assert abs(value - printed) <= tol, (value, printed, tol)
    n += 1


# Exercise 1: complete market, states (slump, boom), equally likely.
psi_b = 1.05 / 2.5                      # stock pays (0, 2.5)
psi_s = 0.92 - psi_b                    # bond pays (1, 1)
check(psi_b, 0.42, 1e-12)
check(psi_s, 0.50, 1e-12)
check(1 / 0.92 - 1, 0.086957, 5e-7)
check(psi_s / 0.92, 0.543478, 5e-7)
check(psi_b / 0.92, 0.456522, 5e-7)
X = (0.5, 3.0)                          # project payoff (slump, boom)
A = X[0] * psi_s + X[1] * psi_b
check(A, 1.51, 1e-12)


def call(K):
    """Price of a call on the project with strike K."""
    return max(X[0] - K, 0) * psi_s + max(X[1] - K, 0) * psi_b


def put(K):
    """Price of a put on the project with strike K."""
    return max(K - X[0], 0) * psi_s + max(K - X[1], 0) * psi_b


check(call(1), 0.84, 1e-12)
check(call(1.5), 0.63, 1e-12)
check(put(1), 0.25, 1e-12)
check(put(1.5), 0.50, 1e-12)
check(call(1) + 1 * 0.92 - put(1), 1.51, 1e-12)
check(call(1.5) + 1.5 * 0.92 - put(1.5), 1.51, 1e-12)

EX = 0.5 * X[0] + 0.5 * X[1]            # expected project payoff
check(EX, 1.75, 1e-12)
rA = EX / A - 1
check(rA, 0.158940, 5e-7)


def face(D):
    """Face value F that makes debt worth D: safe if F <= 0.5, else risky."""
    return D / 0.92 if D <= 0.5 * 0.92 else (D - X[0] * psi_s) / psi_b


def returns(D):
    """(F, rD, rE, E) for debt raised D; expected returns use true probabilities."""
    F = face(D)
    ED = 0.5 * min(X[0], F) + 0.5 * min(X[1], F)
    E = A - D
    return F, ED / D - 1, (EX - ED) / E - 1, E


check(0.5 * 0.92, 0.46, 1e-12)
F1, rD1, rE1, E1 = returns(1.0)
check(F1, 1.785714, 5e-7)
check(rD1, 0.142857, 5e-7)
check(rE1, 0.190476, 5e-7)
check(E1, 0.51, 1e-12)
check(0.5 * 0.5 + 0.5 * F1, 1.142857, 5e-7)
check(0.5 * (3 - F1), 0.607143, 5e-7)
check((1 / A) * rD1 + (E1 / A) * rE1, rA, 1e-12)
check(F1 / 1 - 1, 0.785714, 5e-7)
check(0.5 / psi_b - 1, 0.190476, 5e-7)
# (e') checkpoints quoted in the text.
F, rD, rE, E = returns(0.46)
check(F, 0.5, 1e-12)
check(rD, 0.086957, 5e-7)
check(rE, 0.190476, 5e-7)
F, rD, rE, E = returns(0.20)
check(F, 0.217391, 5e-7)
check(rE, 0.169930, 5e-7)
check(E, 1.31, 1e-12)
check(0.20 / E, 0.152672, 5e-7)
check(rA - (1 / 0.92 - 1), 0.071984, 5e-7)
check(rA + (0.20 / E) * (rA - (1 / 0.92 - 1)), rE, 1e-12)
check(1.51, A, 1e-12)
# (f): raise 1.1, pay 0.1 dividend.
Ff, rDf, rEf, Ef = returns(1.1)
check(Ff, 2.023810, 5e-7)
check(Ef, 0.41, 1e-12)
check(Ef + 0.1, 0.51, 1e-12)

rows = []
for i in range(1, 101):
    D = i / 100
    F, rD, rE, E = returns(D)
    assert abs((D / A) * rD + (E / A) * rE - rA) < 1e-12   # MM: WACC = rA
    rows.append(f"{D:.2f} & {F:.4f} & {100 * rD:.2f} & {100 * rE:.2f} & "
                f"{100 * rA:.2f} & {E:.2f} & {A:.2f} \\\\")
Path(__file__).with_name("PS2-solutions-table.tex").write_text(
    "% Generated by PS2-solutions_check.py -- do not edit by hand.\n"
    + "\n".join(rows) + "\n", encoding="utf-8")

# Exercise 2 (millions of dollars).
