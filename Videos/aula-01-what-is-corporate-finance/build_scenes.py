"""Concatenate scenes_common.py + scenes_g*.py into scenes.py (one module to render).

explainer-compile reads a single render directory, media/videos/scenes/<quality>/, so every
beat must come from one module. The groups stay the source; scenes.py is generated.
Run: python build_scenes.py
"""
import pathlib, re

here = pathlib.Path(__file__).parent
SENTINEL = "# ---- scenes ----"
parts = [(here / "scenes_common.py").read_text(encoding="utf-8").rstrip() + "\n"]
for g in sorted(here.glob("scenes_g*.py"), key=lambda p: int(re.findall(r"\d+", p.stem)[0])):
    src = g.read_text(encoding="utf-8")
    if SENTINEL not in src:
        raise SystemExit(f"{g.name}: missing the '{SENTINEL}' line")
    parts.append(f"\n\n# {'=' * 66} {g.stem}\n" + src.split(SENTINEL, 1)[1].strip() + "\n")
out = "# GENERATED by build_scenes.py from scenes_common.py + scenes_g*.py. Do not edit.\n" + "".join(parts)
(here / "scenes.py").write_text(out, encoding="utf-8")
print(f"scenes.py: {out.count(chr(10))} lines, {len(re.findall(r'^class Beat', out, re.M))} beats")
